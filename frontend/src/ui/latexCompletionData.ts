/**
 * Commands and environments the editor offers as you type (issue #192).
 * This is static data in a chunk of its own. The editor imports it the first time it completes
 * something, so it isn't part of the initial load.
 *
 * Arguments are CodeMirror snippet templates: `#{name}` is a tab stop that starts out holding
 * "name", and `#{}` is an empty one. Don't write `\{` or `\}`: the snippet parser reads those as
 * escaped braces.
 */

/** A command: its name without the backslash, its arguments as a snippet, and what it does. */
export type LatexCommand = readonly [name: string, args: string, info: string];

/** An environment: its name, what it is, the arguments after `\begin{name}`, and its body. */
export type LatexEnvironment = readonly [name: string, info: string, args?: string, body?: string];

