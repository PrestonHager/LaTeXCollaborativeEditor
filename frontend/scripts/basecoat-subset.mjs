/**
 * Builds src/styles/basecoat-vega.css from Basecoat's Vega style pack, keeping only the
 * components we use. The full pack styles every component, which roughly 10x's our CSS.
 * Run from frontend/: npm run basecoat:subset
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

// Add a component here (by its comment name in vega.css) when the app starts using it.
export const COMPONENTS = ['Button', 'Badge', 'Command', 'Dialog', 'Dropdown Menu', 'Popover', 'Checkbox', 'Label', 'Native Select', 'Empty', 'Item', 'Progress'];

const require = createRequire(import.meta.url);
const __dirname = dirname(fileURLToPath(import.meta.url));
export const OUTPUT_PATH = join(__dirname, '..', 'src', 'styles', 'basecoat-vega.css');

export function readVegaSource() {
  const pkgDir = dirname(require.resolve('basecoat-css/package.json'));
  return readFileSync(join(pkgDir, 'dist', 'styles', 'vega.css'), 'utf8');
}

/** Keep only the `/* Name *\/` sections of vega.css that are listed in `components`. */
export function buildSubset(source, components = COMPONENTS) {
  // First, drop the leading comment and the @layer wrapper so we're left with the sections.
  const start = source.indexOf('@layer components {');
  const end = source.lastIndexOf('}');
  if (start < 0 || end < start) throw new Error('vega.css layout changed, update basecoat-subset.mjs');
  const body = source.slice(start + '@layer components {'.length, end);

  // Then split on the section comments. The first comment (Accordion) sits outside the layer.
  const sections = new Map();
  sections.set('Accordion', '');
  let current = 'Accordion';
  for (const line of body.split('\n')) {
    const match = /^ {2}\/\* ([A-Za-z ]+) \*\/$/.exec(line);
    if (match) {
      current = match[1];
      sections.set(current, '');
      continue;
    }
    sections.set(current, sections.get(current) + line + '\n');
  }

  // Finally, put the kept sections back in a layer, in the same order as the source.
  const missing = components.filter((name) => !sections.has(name));
  if (missing.length) throw new Error(`Not found in vega.css: ${missing.join(', ')}`);
  const kept = [...sections].filter(([name]) => components.includes(name));
  const parts = kept.map(([name, css]) => `  /* ${name} */\n${css.replace(/\n+$/, '')}\n`);
  return [
    '/* Generated by scripts/basecoat-subset.mjs from basecoat-css/dist/styles/vega.css. Do not edit. */',
    '@layer components {',
    parts.join('\n'),
    '}',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT_PATH, buildSubset(readVegaSource()));
  console.log(`Wrote ${OUTPUT_PATH}`);
}
